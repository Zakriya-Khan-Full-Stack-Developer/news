import fs from 'node:fs';
import path from 'node:path';

// ─────────────────────────────────────────────────────────────────────────────
// NameVerse — prune the source dataset out of the publish payload.
//
// WHY THIS EXISTS
// public/names/** is 217 MB across 13,805 JSON files. Every one of them is read
// at BUILD time to prerender the name pages — and then is completely unused at
// request time. Netlify publishes `public/` as static assets, so before this
// script ran, every single deploy uploaded 217 MB that no visitor or crawler
// would ever fetch. That is pure build time and pure deploy size for nothing.
//
// WHAT IS KEPT
// `_search-index.json`, one per tradition. Those ARE fetched at runtime by
// HomepageSearch, SearchClient and PopularityClient, so they must ship.
//
// SAFETY
// This deletes files from your working tree. It refuses to run unless it is on
// Netlify (NETLIFY=true), so a local `npm run build` can never destroy the
// dataset. It also refuses to run unless the build actually produced pages, so
// it cannot delete the dataset after a failed build.
//
// Run after `next build` — the HTML has already been generated by then.
// ─────────────────────────────────────────────────────────────────────────────

const ROOT = path.resolve(process.cwd());
const NAMES_DIR = path.join(ROOT, 'public', 'names');
const PRERENDER_MANIFEST = path.join(ROOT, '.next', 'prerender-manifest.json');
const RELIGIONS = ['islamic', 'christian', 'hindu', 'italian'];

if (process.env.NETLIFY !== 'true') {
  console.log('prune: not running on Netlify (NETLIFY !== "true") — leaving the dataset alone.');
  process.exit(0);
}

if (!fs.existsSync(PRERENDER_MANIFEST)) {
  console.error('prune: .next/prerender-manifest.json is missing — the build did not finish.');
  console.error('prune: refusing to delete the dataset after a failed build.');
  process.exit(1);
}

if (!fs.existsSync(NAMES_DIR)) {
  console.log('prune: public/names does not exist — nothing to do.');
  process.exit(0);
}

let removed = 0;
let removedBytes = 0;
let kept = 0;
let keptBytes = 0;

for (const rel of RELIGIONS) {
  const dir = path.join(NAMES_DIR, rel);
  if (!fs.existsSync(dir)) continue;
  for (const entry of fs.readdirSync(dir)) {
    if (!entry.endsWith('.json')) continue;
    const full = path.join(dir, entry);
    const size = fs.statSync(full).size;
    // The four search indexes are the ONLY files in here that anything fetches
    // at runtime. Everything else exists solely to feed the build.
    if (entry === '_search-index.json') {
      kept++;
      keptBytes += size;
      continue;
    }
    fs.unlinkSync(full);
    removed++;
    removedBytes += size;
  }
}

const mb = (n) => (n / 1024 / 1024).toFixed(1);
console.log(
  `prune: removed ${removed.toLocaleString()} build-only JSON files (${mb(removedBytes)} MB); ` +
    `kept ${kept} search index(es) (${mb(keptBytes)} MB).`
);
console.log('prune: the dataset itself is still in git — only the deployed payload was trimmed.');
