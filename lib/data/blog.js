// ─────────────────────────────────────────────────────────────────────────────
// Blog data helpers.
//
// The article bodies live in public/data/blog-posts.json (read through
// getBlogPosts()). Everything a template needs to DERIVE from that data lives
// here, so the index page, the article page, the blog sitemap and the build
// verifier (scripts/verify-blog.mjs) all agree:
//
//   • reading time is computed from the words actually published — never a
//     hand-typed "7 min read" on a 250-word post;
//   • section text is split into real paragraphs;
//   • headings get stable anchor ids for the table of contents;
//   • related posts are chosen by shared category / tags.
// ─────────────────────────────────────────────────────────────────────────────

import fs from 'node:fs';
import path from 'node:path';
import { getBlogPosts } from './names-data.js';

export const BLOG_WORDS_PER_MINUTE = 220;
const OG_DIR = path.join(process.cwd(), 'public', 'blog', 'og');

function words(text) {
  return String(text || '')
    .split(/\s+/)
    .filter(Boolean).length;
}

// Every piece of reader-visible prose in a post, in reading order.
export function postText(post) {
  const c = post?.content || {};
  const parts = [c.introduction || ''];
  for (const t of c.keyTakeaways || []) parts.push(t);
  for (const s of c.sections || []) {
    parts.push(s.title || '', s.content || '');
    for (const n of s.names || []) parts.push(n.name || '', n.meaning || '', n.origin || '', n.note || '');
    for (const b of s.bullets || []) parts.push(b);
  }
  for (const f of c.faqs || []) parts.push(f.q || '', f.a || '');
  return parts.join(' ');
}

export function wordCount(post) {
  return words(postText(post));
}

export function readMinutes(post) {
  return Math.max(1, Math.round(wordCount(post) / BLOG_WORDS_PER_MINUTE));
}

export function readTimeLabel(post) {
  return `${readMinutes(post)} min read`;
}

// Section bodies are stored as one string; blank lines separate paragraphs.
export function paragraphs(text) {
  return String(text || '')
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s*\n\s*/g, ' ').trim())
    .filter(Boolean);
}

export function headingId(title, index = 0) {
  const base = String(title || '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64);
  return base || `section-${index + 1}`;
}

export function isPublishable(post) {
  return Boolean(post && post.id && post.content?.introduction && post.content?.sections?.length);
}

// Newest first; ties broken by title so the order is deterministic.
export function getPublishedPosts() {
  return getBlogPosts()
    .filter(isPublishable)
    .sort((a, b) => {
      const d = String(b.publishDate || '').localeCompare(String(a.publishDate || ''));
      return d !== 0 ? d : String(a.title).localeCompare(String(b.title));
    });
}

export function getPostById(id) {
  return getPublishedPosts().find((p) => p.id === id) || null;
}

function asList(value) {
  if (Array.isArray(value)) return value;
  return String(value || '')
    .split(',')
    .map((v) => v.trim())
    .filter(Boolean);
}

export function getRelatedPosts(post, limit = 3) {
  if (!post) return [];
  const tags = new Set(asList(post.tags).map((t) => String(t).toLowerCase()));
  return getPublishedPosts()
    .filter((p) => p.id !== post.id)
    .map((p) => {
      let score = p.category === post.category ? 3 : 0;
      for (const t of asList(p.tags)) if (tags.has(String(t).toLowerCase())) score += 1;
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || String(b.p.publishDate).localeCompare(String(a.p.publishDate)))
    .slice(0, limit)
    .map((x) => x.p);
}

export function getCategories(posts = getPublishedPosts()) {
  const counts = new Map();
  for (const p of posts) counts.set(p.category, (counts.get(p.category) || 0) + 1);
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])))
    .map(([name, count]) => ({ name, count, id: headingId(name) }));
}

// Per-post 1200×630 share card generated by scripts/generate-share-images.py.
// Falls back to null (callers then use the site default) when the card has not
// been generated yet, so a new post can never reference a missing image.
export function shareImageFor(post) {
  if (!post?.id) return null;
  const file = path.join(OG_DIR, `${post.id}.png`);
  if (!fs.existsSync(file)) return null;
  return {
    url: `/blog/og/${post.id}.png`,
    width: 1200,
    height: 630,
    alt: post.title,
  };
}

export function formatDate(iso, opts = { year: 'numeric', month: 'long', day: 'numeric' }) {
  if (!iso) return '';
  const d = new Date(`${String(iso).slice(0, 10)}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', { ...opts, timeZone: 'UTC' });
}

const moduleApi = {
  BLOG_WORDS_PER_MINUTE,
  postText,
  wordCount,
  readMinutes,
  readTimeLabel,
  paragraphs,
  headingId,
  isPublishable,
  getPublishedPosts,
  getPostById,
  getRelatedPosts,
  getCategories,
  shareImageFor,
  formatDate,
};

export default moduleApi;
